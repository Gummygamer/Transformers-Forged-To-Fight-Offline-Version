#!/usr/bin/env python3
"""Write proofs/Data.bend from the server's own data, so the laws check what ships:
the statMods catalog (Server/data/stat_modifiers.json) and the per-bot kit table
(kit_abilities in Server/gamedata.lbl). Run by proofs/check.sh before every proof run."""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
mods = json.loads((root / "Server/data/stat_modifiers.json").read_text())
appears = json.loads((root / "Server/data/stat_mod_appears.json").read_text())
campaign = json.loads((root / "Server/data/campaign.json").read_text())
campaign_batches = {k: v for k, v in json.loads((root / "Server/data/campaign_batches.json").read_text()).items() if not k.startswith("_")}
status = json.loads((root / "proofs/effect_status.json").read_text())
src = (root / "Server/gamedata.lbl").read_text()
body = re.search(r"^function kit_abilities\(bid: text\): a list of text\n(.*?)\nend\n", src, re.S | re.M)
if not body:
    sys.exit("gen_data: kit_abilities not found in Server/gamedata.lbl")
kits = re.findall(r'bid == "([^"]+)" then\s*\[([^\]]*)\]', body.group(1))
if not kits:
    sys.exit("gen_data: no kit branches parsed from kit_abilities")

TA = {"self": "OnSelf{}", "opponent": "OnOpponent{}", "owner": "OnOwner{}", "tower": "OnTower{}", "opp_tower": "OnOppTower{}"}
MT = {"buff": "Buff{}", "debuff": "Debuff{}", "passive": "Passive{}"}

def s(x):
    return json.dumps(x)

out = ["import Base", "import ./Abilities.bend as A", "import ./Campaign.bend as C", "",
       "# GENERATED by proofs/gen_data.py from Server/data/stat_modifiers.json and",
       "# kit_abilities in Server/gamedata.lbl. Do not edit; rerun the generator.", "",
       "def catalog() -> List<&2, A.Row>:", "  ["]
rows = [f"    A.Row{{{s(k)}, A.{TA[v['ta']]}, A.{MT[v['mt']]}, {s(v['t'])}}}" for k, v in mods.items()]
out.append(",\n".join(rows))
out += ["  ]", "", "def kits() -> List<&2, A.Kit>:", "  ["]
entries = []
for bid, ids in kits:
    names = re.findall(r'"([^"]+)"', ids)
    entries.append(f"    A.Kit{{{s(bid)}, [{', '.join(s(n) for n in names)}]}}")
out.append(",\n".join(entries))
out += ["  ]", ""]

# The ability cards (statModAppears) and what each row does that a card may quote.
# A moment of a fight, as a description names it and as a trigger id spells it.
MOMENTS = {"special": (r"\bspecials?\b", "Special"), "crit": (r"\bcrit", "Crit"),
           "block": (r"\bblock", "Block"), "hit": (r"\b(hits?|strikes?)\b", "Hit")}

def says(text):
    return [m for m, (word, _) in MOMENTS.items() if re.search(word, text, re.I)]

def fires(tr):
    return sorted({m for t in tr for m, (_, part) in MOMENTS.items() if part in t})

def strs(xs):
    return "[" + ", ".join(s(x) for x in xs) + "]"

def card(k, v):
    icon = ", ".join(f"{ord(ch)}n" for ch in v.get("t", ""))
    nums = ", ".join(f"{n}n" for n in re.findall(r"\d+", v.get("l", "")))
    return f"    A.Card{{{s(k)}, {s(v.get('a', ''))}, {s(v.get('l', ''))}, [{icon}], [{nums}], {strs(says(v.get('l', '')))}}}"

def whole(x):
    return max(0, round(float(x)))

out += ["def cards() -> List<&2, A.Card>:", "  [", ",\n".join(card(k, v) for k, v in appears.items()), "  ]", "",
        "def mags() -> List<&2, A.Mag>:", "  [",
        ",\n".join(f"    A.Mag{{{s(k)}, {whole(v['m'] * 100)}n, {whole(v['d'])}n, {whole(v['c'] * 100)}n, {strs(fires(v.get('tr', [])))}}}" for k, v in mods.items()),
        "  ]", ""]

def fn_body(name):
    m = re.search(r"^(?:public )?function " + name + r"\(.*?\n(.*?)\nend\n", src, re.S | re.M)
    if not m:
        sys.exit("gen_data: " + name + " not found in Server/gamedata.lbl")
    return m.group(1)

ratios = [round(float(x) * 100) for x in re.findall(r"[0-9.]+", re.search(r"\[([^\]]*)\]", fn_body("special_damage_ratios")).group(1))]
max_sp = int(re.findall(r"^\s*(\d+)\s*$", fn_body("max_special_attacks"), re.M)[-1])
growth = fn_body("level_growth").strip().splitlines()[-1].strip()
rank = re.search(r"1 \+ ([0-9.]+) \* to_decimal\(max\(1, rank\) - 1\)", fn_body("base_stats"))
# Stats.bend writes the stat factors with these exact fractions; a change here must change it too.
if growth != "0.025" or not rank or rank.group(1) != "0.35":
    sys.exit("gen_data: level_growth or the rank multiplier changed; update proofs/Stats.bend")
out += ["# special_damage_ratios, in hundredths, and max_special_attacks.",
        "def special_ratios() -> List<&2, Nat>:",
        "  [" + ", ".join(f"{r}n" for r in ratios) + "]", "",
        "def max_special_attacks() -> Nat:", f"  {max_sp}n", ""]
roster = re.findall(r'RosterEntry \{ bid: "([^"]+)"', "".join(fn_body(f) for f in ("roster_part_1_a", "roster_part_1_b", "roster_part_2_a", "roster_part_2_b", "roster_part_3")))
if not roster:
    sys.exit("gen_data: no roster entries parsed")
out += ["# The bots of the roster (roster_part_* in Server/gamedata.lbl).", "def roster() -> List<&2, String>:", "  [",
        ",\n".join(f"    {s(b)}" for b in roster), "  ]", ""]
# The verification campaign (Server/data/campaign.json, campaign_batches.json) and the verified effect classes.
AXIS = {"effect": "C.OnEffect{}", "trigger": "C.OnTrigger{}"}

def probe(v):
    return f"C.Probe{{{s(v['id'])}, A.{TA[v['ta']]}, A.{MT[v['mt']]}, {s(v['t'])}, {strs(v.get('tr', []))}, {whole(v['c'] * 100)}n}}"

def batch(name, b):
    for k, v in b["rows"].items():
        if v.get("id") != k:
            sys.exit(f"gen_data: campaign row {k} has id {v.get('id')}")
    return f"    C.Batch{{{s(name)}, {AXIS[b['axis']]}, [{', '.join(probe(v) for v in b['rows'].values())}]}}"

out += ["# Server/data/campaign_batches.json and campaign.json: the batches, the active one and the probe bot.", "def batches() -> List<&2, C.Batch>:", "  [",
        ",\n".join(batch(k, b) for k, b in campaign_batches.items()), "  ]", "",
        "def campaign_active() -> String:", f"  {s(campaign['active'])}", "",
        "def campaign_bot() -> String:", f"  {s(campaign['bot'])}", "",
        "# Effect classes verified live (proofs/effect_status.json).", "def verified() -> List<&2, String>:",
        "  " + strs([k for k, v in status.items() if not k.startswith("_") and v.get("mark") == "live"]), ""]
(root / "proofs/Data.bend").write_text("\n".join(out))
