#!/usr/bin/env python3
"""Write ABILITY_GLOSSARY.md from the tables the server serves: the statMods catalog
(Server/data/stat_modifiers.json), the ability cards (Server/data/stat_mod_appears.json),
the kit table (bot_abilities in Server/gamedata.lbl) and the verification status of each
effect class (proofs/effect_status.json). Run by proofs/check.sh; do not edit the output."""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
mods = json.loads((root / "Server/data/stat_modifiers.json").read_text())
cards = json.loads((root / "Server/data/stat_mod_appears.json").read_text())
status = json.loads((root / "proofs/effect_status.json").read_text())
src = (root / "Server/gamedata.lbl").read_text()
body = re.search(r"public function bot_abilities\(bid: text\): a list of text\n(.*?)\nend\n", src, re.S)
if not body:
    sys.exit("gen_glossary: bot_abilities not found in Server/gamedata.lbl")
kits = [(bid, re.findall(r'"([^"]+)"', ids)) for bid, ids in re.findall(r'bid == "([^"]+)" then\s*\[([^\]]*)\]', body.group(1))]

LANDS = {"self": "the carrier", "opponent": "the opponent", "owner": "the owner",
         "tower": "the carrier's tower", "opp_tower": "the opponent's tower"}
MARK = {"live": "👁 live", "served": "📡 served", "binary": "📄 binary"}

def mark(cls):
    return MARK[status[cls]["mark"]] if cls in status else "⚠ untested"

def pct(x):
    return f"{round(float(x) * 100)}%"

def secs(d):
    d = float(d)
    return "indefinite" if d < 0 else ("instant" if d == 0 else f"{d:g} s")

def icon(t):
    return " ".join(f"U+{ord(c):04X}" for c in t) or "none"

def cell(x):
    return str(x).replace("|", "\\|")

carriers = {}
for bid, ids in kits:
    for a in ids:
        carriers.setdefault(a, []).append(bid)
carried = [a for a in mods if a in carriers]

out = ["# Ability glossary", "",
       "GENERATED by `proofs/gen_glossary.py` from the tables the server serves; do not edit.",
       "Change `Server/data/stat_modifiers.json`, `Server/data/stat_mod_appears.json`,",
       "`bot_abilities` in `Server/gamedata.lbl` or `proofs/effect_status.json`, then run",
       "`proofs/check.sh`. How to author an ability: `ABILITY_AUTHORING.md`.", "",
       "The law `abilities_carded` (`proofs/LAWS.bend`) checks every card below against its row:",
       "every number it quotes is the row's, it states the strength and duration, and it names no",
       "moment of a fight the row does not fire on.", "",
       "## Abilities bots carry", "",
       "| ability | title | icon | lands on | kind | effect | fires on | chance | strength | lasts | status | carried by |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for a in carried:
    r, c = mods[a], cards.get(a, {})
    out.append("| " + " | ".join(cell(x) for x in [
        f"`{a}`", c.get("a", "—"), icon(c.get("t", "")), LANDS.get(r["ta"], r["ta"]), r["mt"], f"`{r['t']}`",
        ", ".join(r.get("tr", [])) or "—", pct(r["c"]), pct(r["m"]) + " of Attack", secs(r["d"]), mark(r["t"]),
        ", ".join(f"`{b}`" for b in carriers[a])]) + " |")
out += ["", "### What the cards say", ""]
for a in carried:
    c = cards.get(a, {})
    out.append(f"- **{c.get('a', a)}** (`{a}`): {c.get('l', '(no card)')}")
out += ["", "## Other rows of the catalog", "",
        "Served to the client but carried by no bot: engine plumbing (floating text, effect",
        "removers, test rows) and effects not yet assigned. Untested ones are not safe to give a",
        "bot until verified (`ABILITY_AUTHORING.md`, the verification campaign).", "",
        "| row | lands on | kind | effect | fires on | status |", "|---|---|---|---|---|---|"]
for a, r in mods.items():
    if a not in carriers:
        out.append("| " + " | ".join(cell(x) for x in [f"`{a}`", LANDS.get(r["ta"], r["ta"]), r["mt"], f"`{r['t']}`",
                                                       ", ".join(r.get("tr", [])) or "—", mark(r["t"])]) + " |")
(root / "ABILITY_GLOSSARY.md").write_text("\n".join(out) + "\n")
